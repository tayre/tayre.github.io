// Tiny dependency-free packager. The checked-in bundle also works via file://.
// Source stays modular for the timer and forecast tests.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const read = name => readFile(new URL(name, import.meta.url), 'utf8');
const core = (await read('core.js')).replace(/^export /gm, '');
const app = (await read('app.js')).replace(/^import .* from '\.\/core\.js';\n/, '');
await writeFile(new URL('still.js', import.meta.url), `// Generated by node build.mjs. Edit app.js / core.js instead.\n(() => {\n'use strict';\n${core}\n${app}\n})();\n`);
const hash = createHash('sha256');
for (const file of ['index.html', 'style.css', 'still.js', 'icon.svg', 'manifest.webmanifest']) hash.update(await read(file));
const version = hash.digest('hex').slice(0, 12);
const sw = (await read('sw.js')).replace(/^const CACHE = .*;/m, `const CACHE = 'still-shell-${version}';`);
await writeFile(new URL('sw.js', import.meta.url), sw);
console.log(`Still packaged · offline version ${version}`);
